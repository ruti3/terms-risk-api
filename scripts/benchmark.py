#!/usr/bin/env python3
"""
Latency benchmark for Terms Risk API.

Usage:
    python scripts/benchmark.py
    python scripts/benchmark.py --fresh   # requires OPENAI_API_KEY in .env

Writes docs/benchmark.md with results.
"""

from __future__ import annotations

import argparse
import json
import os
import statistics
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

os.environ.setdefault("X402_ENABLED", "false")
os.environ.setdefault("X402_SKIP_PAYMENT", "true")

from dotenv import load_dotenv

load_dotenv(ROOT / ".env")

from fastapi.testclient import TestClient

from app.main import app

REQUEST_BODY = {
    "url": "https://www.cloudflare.com/website-terms/",
    "use_case": "Can I scrape and commercially reuse public listings?",
}


def percentile(values: list[float], p: float) -> float:
    if not values:
        return 0.0
    ordered = sorted(values)
    idx = int(len(ordered) * p / 100)
    return ordered[min(idx, len(ordered) - 1)]


def bench(fn, iterations: int) -> dict:
    times: list[float] = []
    status = None
    for _ in range(iterations):
        start = time.perf_counter()
        result = fn()
        times.append((time.perf_counter() - start) * 1000)
        status = getattr(result, "status_code", None)
    return {
        "iterations": iterations,
        "status": status,
        "min_ms": round(min(times), 2),
        "p50_ms": round(statistics.median(times), 2),
        "p95_ms": round(percentile(times, 95), 2),
        "max_ms": round(max(times), 2),
        "mean_ms": round(statistics.mean(times), 2),
    }


def write_markdown(results: dict, out_path: Path) -> None:
    lines = [
        "# Benchmark",
        "",
        "Generated by `python scripts/benchmark.py`.",
        "",
        "Environment: FastAPI TestClient (in-process). Fresh analysis requires network + OpenAI.",
        "",
        "## Results",
        "",
        "| Endpoint | Iterations | p50 | p95 | mean | min | max |",
        "|----------|------------|-----|-----|------|-----|-----|",
    ]
    for name, r in results.items():
        if r.get("skipped"):
            continue
        lines.append(
            f"| {name} | {r['iterations']} | {r['p50_ms']} ms | {r['p95_ms']} ms | "
            f"{r['mean_ms']} ms | {r['min_ms']} ms | {r['max_ms']} ms |"
        )

    lines.extend(
        [
            "",
            "## Notes",
            "",
            "- **Health** — no external I/O.",
            "- **Cache hit** — second identical request after warm-up (includes fetch + cache read).",
            "- **Fresh** — first request or new url+use_case; dominated by HTTP fetch + OpenAI latency.",
            "",
            "Re-run locally:",
            "",
            "```bash",
            "python scripts/benchmark.py",
            "python scripts/benchmark.py --fresh  # needs OPENAI_API_KEY",
            "```",
            "",
        ]
    )

    if results.get("POST /terms-risk (fresh)", {}).get("skipped"):
        lines.append(
            "_Fresh analysis benchmark skipped (pass `--fresh` with OPENAI_API_KEY set)._"
        )
    else:
        fresh = results.get("POST /terms-risk (fresh)", {})
        lines.append(f"_Fresh analysis HTTP status: {fresh.get('status')}_")

    out_path.write_text("\n".join(lines) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--fresh", action="store_true", help="Run fresh analysis benchmark")
    parser.add_argument("--iterations", type=int, default=50)
    args = parser.parse_args()

    results: dict = {}

    with TestClient(app) as client:
        results["GET /health"] = bench(lambda: client.get("/health"), args.iterations)

        warm = client.post("/terms-risk", json=REQUEST_BODY)
        if warm.status_code == 200:
            results["POST /terms-risk (cache hit)"] = bench(
                lambda: client.post("/terms-risk", json=REQUEST_BODY),
                min(args.iterations, 20),
            )
        else:
            results["POST /terms-risk (cache hit)"] = {
                "skipped": True,
                "reason": f"warm-up failed: {warm.status_code}",
            }

        if args.fresh and os.getenv("OPENAI_API_KEY"):
            unique_body = {
                **REQUEST_BODY,
                "use_case": f"Benchmark run at {time.time():.0f}",
            }
            fresh = bench(
                lambda: client.post("/terms-risk", json=unique_body),
                3,
            )
            results["POST /terms-risk (fresh)"] = fresh
        else:
            results["POST /terms-risk (fresh)"] = {"skipped": True}

    out = ROOT / "docs" / "benchmark.md"
    write_markdown(results, out)
    print(json.dumps(results, indent=2))
    print(f"\nWrote {out}")


if __name__ == "__main__":
    main()
